"""Write genscale/mr_<method>_k{2,4}_lr5p3e3_wd01.yaml (multi-rewrite arms) once a method's export exists.

S1 + k x Rw(S2): dclm_8m_0 at weight 1 (one epoch) + k view sources over the first N rows of
dclm_8m_1 (N = 4M for k=2, 2M for k=4). Token-matched: the slot is ~10.1B tokens like S1, and every
view gets the same weight w = 1262.1 / sum_v L_v (L_v = view tok/doc), so every rewrite is seen the
same ~w * 8M / N times.

    python setup/make_multirewrite_configs.py <method> [--launch]
"""

import json
import os
import subprocess
import sys

LC = "/checkpoint/dream-sc-3/scottg/pretrain/lingua-clean"
CFG = f"{LC}/apps/main/configs/experiments/genscale"
DATA = "/home/sgeng/scottg/pretrain/assets/data"
WIKI0 = "dclm_rewrites/dclm_8m_1_qwen35_9b_wiki_g1_max4096"
S1_L = 1262.1
DESC = {
    "iid": "iid wiki rewrites at T=1 (view 0 = the existing 9B wiki rewrite)",
    "t12": "wiki rewrites at T=1.2, no top_p / min_p",
    "gacha": "Gacha-decoded wiki rewrites (simplescale.harnesses.gacha:rewrite_wiki)",
    "nemo": "Nemotron-CC prompt mixture: wiki, diverse_qa (k=2) + distill, knowledge_list (k=4)",
    "wofmt": "wiki + (k-1) WebOrganizer formats sampled at S2's format rates (excl. Knowledge Article etc.)",
}


def views(method, k):
    n = "4m" if k == 2 else None
    out = []
    for g in range(k):
        if g == 0 and method in ("iid", "nemo", "wofmt"):
            out.append(WIKI0)
        else:
            out.append(f"dclm_rewrites/dclm_8m_1_rewrite_first{'4m' if g < 2 else '2m'}_qwen35_9b_{method}_g{g}_max4096")
    return out


def main():
    method, launch = sys.argv[1], "--launch" in sys.argv
    base = open(f"{CFG}/mr_repeat_k2_lr5p3e3_wd01.yaml").read()
    for k, N in ((2, 4_000_000), (4, 2_000_000)):
        vs = views(method, k)
        L = [json.load(open(f"{DATA}/{v}/dataset.json"))["qwen35_tokens_per_doc_incl_eos"] for v in vs]
        w = S1_L / sum(L)
        epochs = w * 8_000_000 / N
        name = f"mr_{method}_k{k}_lr5p3e3_wd01"
        head = (
            f"# Multi-rewrite study: S1 + {k}xRw(S2), {DESC[method]}.\n"
            f"# dclm_8m_0 (weight 1, one epoch) + {k} Qwen3.5-9B rewrite views of the first {N // 10**6}M rows of dclm_8m_1.\n"
            f"# Token-matched slot (~10.1B tokens): each view weight = 1262.1 / sum(view tok/doc {', '.join(f'{x:.0f}' for x in L)})\n"
            f"# = {w:.4f}, so each rewrite is seen ~{epochs:.2f}x. Compare to genscale/mr_repeat_k{k}_lr5p3e3_wd01.\n"
            f"# Generated by setup/make_multirewrite_configs.py. Everything else as genscale/mr_repeat_k{k}_lr5p3e3_wd01.yaml.\n#\n"
            f"# Launch:\n#   LINGUA_VENV=$PWD/.venv-kd LINGUA_EVAL_VENV=$PWD/.venv HF_HUB_OFFLINE=1 \\\n"
            f"#   CONFIG=experiments/genscale/{name} NNODES=4 STEPS_OVERRIDE=19074 bash scripts/launch_pretrain.sh\n"
        )
        body = base[base.index("name:"):]
        body = body.replace("mr-repeat-k2", f"mr-{method}-k{k}").replace("mr_repeat_k2", name.replace("_lr5p3e3_wd01", ""))
        old = "  sources:\n    dclm_subsets/dclm_8m_0: 1.0\n    dclm_subsets/dclm_8m_1: 1.0\n  source_max_docs:\n    dclm_subsets/dclm_8m_1: 4000000\n"
        assert old in body
        new = ("  sources:\n    dclm_subsets/dclm_8m_0: 1.0\n" + "".join(f"    {v}: {w:.4f}\n" for v in vs)
               + "  source_max_docs:\n" + "".join(f"    {v}: {N}\n" for v in vs))
        body = body.replace(old, new)
        dump = "  dump:\n    every: 1000\n    keep: -1\n"
        assert dump in body
        body = body.replace(dump, "  dump:\n    every: 500               # these runs get preempted on comm_shared; 1000 lost whole windows\n"
                                  "    keep: 2                  # 1000-multiples are eval checkpoints (eval.keep -1), kept regardless\n")
        open(f"{CFG}/{name}.yaml", "w").write(head + body)
        print(f"{name}: w={w:.4f} epochs={epochs:.2f} L={L}")
        if launch:
            env = {k_: v_ for k_, v_ in os.environ.items() if k_.lower() not in ("http_proxy", "https_proxy", "no_proxy")}
            env.update(LINGUA_VENV=f"{LC}/.venv-kd", LINGUA_EVAL_VENV=f"{LC}/.venv", HF_HUB_OFFLINE="1",
                       CONFIG=f"experiments/genscale/{name}", NNODES="4", STEPS_OVERRIDE="19074")
            subprocess.run(["bash", "scripts/launch_pretrain.sh"], cwd=LC, env=env, check=True)


if __name__ == "__main__":
    main()
