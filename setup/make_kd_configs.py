"""Configs for the w1152 KD + synthetic-data baselines (plan: LR 2.1e-3, bs256, wd 0.1; see the w1152 LR sweep).

Student and data pipeline are the data_constrainedv2 w1152 unique-DCLM runs; only LR, the loss and the data mix change.
  B  2x Chinchilla, DCLM only: CE baseline + KD alpha in ALPHAS                       (kd_w1152/b_*)
  C  2x, best KD alphas x synthetic fraction r x {rw_gacha, rw_direct}               (--stage c --alphas ...)
  D  4x main + 2x decay branch for a list of (alpha, arm, r)                          (--stage d --specs ...)
KD: (1 - alpha) CE + alpha KL(teacher || student), T = 1, teacher Qwen3-8B-Base on every token. Synthetic data replaces
a fraction r of the DCLM sequences (lingua/token_stream.py MixedTokenStream). The final eval adds the rw val sets and
the OLMES downstream suite (scripts/launch_olmes_suite.py DOWNSTREAM). Runs are launched by
scripts/dataconstrained_orchestrate.py --group kd_w1152.

    .venv-kd/bin/python setup/make_kd_configs.py --stage b
    .venv-kd/bin/python setup/make_kd_configs.py --stage c --alphas 0.5 0.7
    .venv-kd/bin/python setup/make_kd_configs.py --stage d --specs 0:dclm:0 0.5:dclm:0 0.5:rw_gacha:0.2
"""
import argparse
import json
import os
import sys

from omegaconf import OmegaConf

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from scripts.launch_olmes_suite import DOWNSTREAM  # noqa: E402

GROUP = "kd_w1152"
OUT = f"{ROOT}/apps/main/configs/experiments/{GROUP}"
TEMPLATE = f"{ROOT}/apps/main/configs/experiments/data_constrainedv2/w1152_u_bs256_lr2e-3_wd0p1.yaml"
DATA = "/home/sgeng/scottg/pretrain/assets/data"
TEACHER = "/home/sgeng/scottg/pretrain/assets/models/Qwen3-8B-Base"
ARMS = {"rw_gacha": f"{DATA}/rw_gacha_qwen3_tokens", "rw_direct": f"{DATA}/rw_direct_qwen3_tokens"}
LR = 2.1e-3
STEPS = {2: 16398, 4: 32796}  # bs256 x 4096 tokens; 20 x 429.9M body+head params per Chinchilla
ALPHAS = [0.1, 0.3, 0.5, 0.7, 0.9]


def tag(x):
    return f"{x:g}".replace(".", "p")


def name(stage, alpha, arm, r, mult):
    s = f"{stage}_" + (f"kd{tag(alpha)}" if alpha else "ce") + (f"_{arm}_r{tag(r)}" if r else "")
    return s + ("" if stage != "d" or mult == 4 else f"_d{mult}x")


def make(stage, alpha, arm, r, mult, main=None):
    n = name(stage, alpha, arm, r, mult)
    c = OmegaConf.load(TEMPLATE)
    c.name = f"{GROUP}-{n}".replace("_", "-")
    c.dump_dir = f"${{oc.env:MIDTRAIN_ROOT}}/experiments/{GROUP}/{n}"
    c.optim.lr = LR
    c.logging.wandb.project = f"lingua-clean-{GROUP}"
    c.steps = STEPS[mult]  # the DCLM stream (template: token_stream_tokens = 4x) is read only up to the horizon
    c.checkpoint.branch_from = None
    if main:  # decay branch of the 4x main, starting from its checkpoint at the 2x decay start
        c.checkpoint.branch_from = f"${{oc.env:MIDTRAIN_ROOT}}/experiments/{GROUP}/{main}/checkpoints/" \
                                   f"{int(STEPS[mult] * 0.9):010d}"
    # The 4x main saves at the 2x branch point (template: extra saves at 1x / 2x decay starts); nothing else does.
    c.checkpoint.extra_save_steps = [int(STEPS[2] * 0.9)] if mult == 4 else []
    if r:
        c.data.token_stream_mix_dir = ARMS[arm]
        c.data.token_stream_mix_ratio = r
        c.data.token_stream_mix_tokens = json.load(open(f"{ARMS[arm]}/meta.json"))["tokens"] - 1
    if alpha:
        c.teacher_model_path = TEACHER
        c.data.use_kl_distillation = True
        c.data.kl_alpha = alpha
        c.data.kl_temperature = 1.0
        c.data.kd_skip_teacher_nll = True
    c.eval.validation.token_streams = list(c.eval.validation.token_streams) + [
        f"{p}/{a}_heldout" for a, p in ARMS.items()]
    c.eval.olmes.tasks = DOWNSTREAM
    c.eval.olmes.model_type = "vllm"
    c.eval.olmes.timeout_hours = 7.0
    os.makedirs(OUT, exist_ok=True)
    with open(f"{OUT}/{n}.yaml", "w") as f:
        f.write(f"# Generated by setup/make_kd_configs.py (stage {stage}, {mult}x, {c.steps} steps, 32 GPUs).\n")
        f.write(OmegaConf.to_yaml(c))
    e = {"name": n, "gpus": 32, "steps": c.steps, "stage": stage, "alpha": alpha, "arm": arm, "r": r, "mult": mult,
         "lr": LR, "bs": 256, "wd": 0.1}
    if main:
        e["main"], e["branch_from"] = main, c.checkpoint.branch_from
    return n, e


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--stage", choices=["b", "c", "d"], required=True)
    ap.add_argument("--alphas", type=float, nargs="+", help="stage c: KD alphas to cross with r and arm")
    ap.add_argument("--specs", nargs="+", help="stage d: alpha:arm:r (arm dclm with r 0 = DCLM only)")
    a = ap.parse_args()
    if a.stage == "b":
        runs = [(x, None, 0, 2, None) for x in [0] + ALPHAS]
    elif a.stage == "c":
        runs = [(x, arm, r, 2, None) for x in a.alphas for arm in ARMS for r in (0.2, 0.4)]
    else:
        runs = []
        for s in a.specs:
            x, arm, r = s.split(":")
            x, r, arm = float(x), float(r), (arm if float(r) else None)
            runs += [(x, arm, r, 4, None), (x, arm, r, 2, name("d", x, arm, r, 4))]
    mpath = f"{OUT}/manifest.json"
    manifest = json.load(open(mpath)) if os.path.exists(mpath) else {}
    for x, arm, r, mult, main_run in runs:
        n, e = make(a.stage, x, arm, r, mult, main_run)
        manifest[n] = e
        print(n)
    with open(mpath, "w") as f:
        json.dump(manifest, f, indent=1)


if __name__ == "__main__":
    main()
