"""Weight soups of finished multisample_dc_w1152 runs (same init and data-order seeds), evaluated like a training
checkpoint. For each soup: average the ingredients' consolidated model weights (fp32, given weights), write
<soup run>/checkpoints/<step>/consolidated/{consolidated.pth, params.json} (model only, no optimizer) plus an empty
.metadata marker (scripts/launch_eval_for_ckpt.py only checks that it exists; eval_olmes skips consolidation when
consolidated/ is complete), and a config whose dump_dir is the soup run; then launch the eval.

    .venv-kd/bin/python setup/make_soups.py [--launch]
"""
import argparse
import os
import subprocess

import torch
import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC_GROUP, GROUP = "multisample_dc_w1152", "multisample_dc_w1152_soups"
RUNS = "/home/sgeng/scottg/pretrain/lingua-runs/runs/midtrain/experiments"
STEP = 24588
# name -> {ingredient run: weight}
SOUPS = {
    **{f"mixkd_kd_l{int(l * 100):02d}": {"r4s_mix_3x_kd8b_a1": l, "real_p12_kd8b_a1": 1 - l} for l in (0.25, 0.5, 0.75)},
    **{f"kd_real_l{int(l * 100):02d}": {"real_p12_kd8b_a1": l, "real_p12": 1 - l} for l in (0.25, 0.5, 0.75)},
    **{f"mix_kd_l{int(l * 100):02d}": {"r4s_mix_3x": l, "real_p12_kd8b_a1": 1 - l} for l in (0.5,)},
    "mixkd_kd_real_eq": {"r4s_mix_3x_kd8b_a1": 1 / 3, "real_p12_kd8b_a1": 1 / 3, "real_p12": 1 / 3},
}


def load(run):
    path = f"{RUNS}/{SRC_GROUP}/{run}/checkpoints/{STEP:010d}/consolidated/consolidated.pth"
    return torch.load(path, map_location="cpu", weights_only=False, mmap=True)["model"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--launch", action="store_true")
    a = ap.parse_args()
    cache = {}
    base_cfg = yaml.safe_load(open(f"{ROOT}/apps/main/configs/experiments/{SRC_GROUP}/real_p12.yaml"))
    os.makedirs(f"{ROOT}/apps/main/configs/experiments/{GROUP}", exist_ok=True)
    for name, parts in SOUPS.items():
        out = f"{RUNS}/{GROUP}/{name}/checkpoints/{STEP:010d}"
        cons = f"{out}/consolidated"
        if not os.path.isfile(f"{cons}/consolidated.pth"):
            for r in parts:
                cache.setdefault(r, load(r))
            keys = next(iter(cache.values())).keys()
            soup = {k: sum(w * cache[r][k].float() for r, w in parts.items()) for k in keys}
            os.makedirs(cons, exist_ok=True)
            torch.save({"model": soup}, f"{cons}/.tmp.pth")
            os.replace(f"{cons}/.tmp.pth", f"{cons}/consolidated.pth")
            params = open(f"{RUNS}/{SRC_GROUP}/real_p12/checkpoints/{STEP:010d}/params.json").read()
            for p in (f"{cons}/params.json", f"{out}/params.json"):
                open(p, "w").write(params)
            open(f"{out}/.metadata", "w").close()
            with open(f"{out}/soup.json", "w") as f:
                f.write(repr(parts))
        cfg = dict(base_cfg)
        cfg["name"] = f"{GROUP}-{name}".replace("_", "-")
        cfg["dump_dir"] = "${oc.env:MIDTRAIN_ROOT}/experiments/" + GROUP + "/" + name
        cpath = f"{ROOT}/apps/main/configs/experiments/{GROUP}/{name}.yaml"
        with open(cpath, "w") as f:
            f.write(f"# Generated by setup/make_soups.py: soup of {parts} at step {STEP} (eval only).\n")
            yaml.safe_dump(cfg, f, sort_keys=False)
        print(name, parts)
        done = os.path.isdir(f"{RUNS}/{GROUP}/{name}/evals/{STEP:010d}")
        if a.launch and not done:
            r = subprocess.run([f"{ROOT}/.venv-kd/bin/python", "scripts/launch_eval_for_ckpt.py", cpath, str(STEP)],
                               cwd=ROOT, env={**os.environ, "PYTHONPATH": ROOT}, capture_output=True, text=True)
            print("  ", (r.stdout + r.stderr).strip().splitlines()[-1] if (r.stdout + r.stderr).strip() else r.returncode)


if __name__ == "__main__":
    main()
