"""Configs for the w1152 multi-sample synthetic-data study (2x Chinchilla, token-matched).

Student, schedule and data pipeline are kd_w1152's CE baseline (LR 2.1e-3, bs256, wd 0.1, WSD over 16,398 steps =
2 x 20 x 429.9M body+head params; data_constrainedv2 w1152 template), so the arms differ only in data:
  dclm_2x        2x Chinchilla of unique DCLM (= kd_w1152/b_ce)
  syn_<arm>      1x DCLM + 1x synthetic: MixedTokenStream with r = 0.5 (every other sequence) from the Qwen3-tokenized,
                 document-shuffled samples of arm <arm> (simplescale.harnesses.multisample, Qwen3.5-9B, 8 samples per
                 source; sources = filtered prefix of dclm_8m_0, setup/build_multisample_manifests.py)
Runs are launched by scripts/dataconstrained_orchestrate.py --group multisample_w1152. A syn_ config is written only
once its token stream exists (re-run this script after tokenizing).

    .venv-kd/bin/python setup/make_multisample_configs.py
"""
import json
import os
import sys

from omegaconf import OmegaConf

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from scripts.launch_olmes_suite import DOWNSTREAM  # noqa: E402

GROUP = "multisample_w1152"
OUT = f"{ROOT}/apps/main/configs/experiments/{GROUP}"
TEMPLATE = f"{ROOT}/apps/main/configs/experiments/data_constrainedv2/w1152_u_bs256_lr2e-3_wd0p1.yaml"
DATA = "/home/sgeng/scottg/pretrain/assets/data"
DCLM = f"{DATA}/dclm_qwen3_tokens"  # dclm_8m_0 + 1 (~20B tokens), same document order as the template's 32M stream
ARMS = ["direct_nothink", "direct_think", "mix", "ideas"]
LR, STEPS, GPUS = 2.1e-3, 16398, 32
QOS = "h100_mdf_scale"  # DM1: explore is often at its group GPU cap (generation workers); scale has room


def stream(arm):
    return f"{DATA}/ms_{arm}_qwen3_tokens"


def make(name, arm=None):
    c = OmegaConf.load(TEMPLATE)
    c.name = f"{GROUP}-{name}".replace("_", "-")
    c.dump_dir = f"${{oc.env:MIDTRAIN_ROOT}}/experiments/{GROUP}/{name}"
    c.optim.lr = LR
    c.steps = STEPS
    c.data.token_stream_dir = DCLM
    c.data.token_stream_tokens = json.load(open(f"{DCLM}/meta.json"))["tokens"] - 1  # TokenStream reads n + 1
    assert c.data.token_stream_tokens >= STEPS * 256 * c.data.seq_len
    c.logging.wandb.project = f"lingua-clean-{GROUP}"
    c.checkpoint.extra_save_steps = []
    if arm:
        c.data.token_stream_mix_dir = stream(arm)
        c.data.token_stream_mix_ratio = 0.5
        c.data.token_stream_mix_tokens = json.load(open(f"{stream(arm)}/meta.json"))["tokens"] - 1
        c.eval.validation.token_streams = list(c.eval.validation.token_streams) + [
            f"{stream(arm)}/ms_{arm}_heldout"]  # the arm's held-out sources (setup/export_multisample.py)
    c.eval.olmes.tasks = DOWNSTREAM
    c.eval.olmes.model_type = "vllm"
    c.eval.olmes.timeout_hours = 7.0
    # fp32 rolling (Paloma) logits are batch_tokens x 151,936 x 4 bytes: the default 32k OOMs an 80 GB H100.
    c.eval.validation.token_stream_rolling_batch_tokens = 8192
    assert c.data.batch_size * GPUS == 256, c.data.batch_size
    with open(f"{OUT}/{name}.yaml", "w") as f:
        f.write(f"# Generated by setup/make_multisample_configs.py (2x, {STEPS} steps, {GPUS} GPUs).\n")
        f.write(OmegaConf.to_yaml(c))
    # 4-node jobs on the preemptible default QoS wait behind priority and get requeued often (QOS above).
    return {"name": name, "gpus": GPUS, "steps": STEPS, "arm": arm, "r": 0.5 if arm else 0, "lr": LR, "bs": 256,
            "wd": 0.1, "qos": QOS}


def main():
    os.makedirs(OUT, exist_ok=True)
    mpath = f"{OUT}/manifest.json"
    manifest = json.load(open(mpath)) if os.path.exists(mpath) else {}
    runs = [("dclm_2x", None)] + [(f"syn_{a}", a) for a in ARMS if os.path.exists(f"{stream(a)}/meta.json")]
    for name, arm in runs:
        manifest[name] = make(name, arm)
        print(name)
    with open(mpath, "w") as f:
        json.dump(manifest, f, indent=1)


if __name__ == "__main__":
    main()
